CREATE TABLE STUDENTS (
    STUDENT_ID NUMBER PRIMARY KEY,
    STUDENT_NAME VARCHAR2(100) NOT NULL,
    DEPARTMENT VARCHAR2(100),
    EMAIL VARCHAR2(100)
);

CREATE TABLE EXAMINATION (
    EXAM_ID NUMBER PRIMARY KEY,
    SUBJECT_NAME VARCHAR2(100) NOT NULL,
    EXAM_DATE DATE NOT NULL,
    EXAM_TIME VARCHAR2(20),
    ROOM_NO VARCHAR2(20)
);

CREATE TABLE RESULTS (
    RESULT_ID NUMBER PRIMARY KEY,
    STUDENT_ID NUMBER NOT NULL REFERENCES STUDENTS(STUDENT_ID),
    EXAM_ID NUMBER NOT NULL REFERENCES EXAMINATION(EXAM_ID),
    MARKS NUMBER(5,2) NOT NULL CHECK (MARKS BETWEEN 0 AND 100),
    GRADE VARCHAR2(5),
    STATUS VARCHAR2(10)
);

